const express = require('express');
const helmet = require('helmet');
const morgan = require('morgan');
const path = require('path');
require('dotenv').config();
const suppliers=require('./routes/suppliers');
const db=require('./db/database');
const app=express();
const port=Number(process.env.PORT||8080);
app.set('view engine','ejs');
app.set('views',path.join(__dirname,'..','views'));
app.use(helmet({contentSecurityPolicy:false}));
app.use(morgan('combined'));
app.use(express.urlencoded({extended:false}));
app.use(express.json());
app.use(express.static(path.join(__dirname,'..','public')));
app.get('/health',(req,res)=>{try{db.prepare('SELECT 1').get();res.json({status:'ok',service:'coffee-supplier-app'});}catch(e){res.status(500).json({status:'error'});}});
app.use(suppliers);
app.use((req,res)=>res.status(404).send('Page not found'));
app.use((err,req,res,next)=>{console.error(err);if(res.headersSent)return next(err);res.status(500).send('Internal server error');});
if(require.main===module) app.listen(port,'0.0.0.0',()=>console.log(`Coffee Supplier application listening on port ${port}`));
module.exports=app;
